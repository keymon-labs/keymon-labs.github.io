// Research notebook: validates the entries (research/<folder>/*.md) and regenerates research/INDEX.md.
// `npm run research` writes the index; `--check` only fails when it is stale. Rules: research/README.md.
import { readFileSync, writeFileSync, existsSync, globSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { parse } from '../scripts/tasks.mjs';

const ROOT = import.meta.dirname;
export const FOLDERS = { projects: 'project', authors: 'author', techniques: 'technique', ideas: 'idea' };
export const ENUM = {
  status: ['captured', 'studied', 'idea', 'planned', 'building', 'shipped', 'dropped'],
  licence_checked: ['repo', 'terms', 'snippet', 'no'],
  reuse: ['ok', 'ask-first', 'ideas-only', 'unknown'],
  free: ['yes', 'freemium', 'no', 'unknown'],
};
const REUSE_ORDER = ['ask-first', 'ideas-only', 'unknown', 'ok'];
const REUSE_NOTE = { 'ask-first': 'ask the owner before any reuse', 'ideas-only': 'learn from it, copy nothing', unknown: 'licence not found, treat as all rights reserved', ok: 'permissive licence: keep its text and add a CREDITS.md row' };
// Licences that can never be `reuse: ok` (see CLAUDE.md "Ask first").
const NOT_OK = /^(none|unknown|proprietary|varies)$|GPL|-NC|-ND/i;

export function load(root = ROOT) {
  return globSync('*/*.md', { cwd: root }).sort().filter((f) => FOLDERS[f.split('/')[0]]).map((path) => {
    const { fm, body } = parse(readFileSync(join(root, path), 'utf8'));
    return { ...fm, path, title: body.match(/^# (.+)$/m)?.[1] ?? path };
  });
}

export function check(entries, root = ROOT) {
  const errors = [];
  for (const e of entries) {
    const bad = (m) => errors.push(`${e.path}: ${m}`);
    const need = ['type', 'summary', 'status', 'captured', ...(['project', 'author'].includes(e.type) ? ['licence', 'licence_checked', 'reuse'] : [])];
    for (const k of need) if (!e[k]) bad(`missing ${k}`);
    if (e.type && e.type !== FOLDERS[e.path.split('/')[0]]) bad(`type ${e.type} does not match its folder`);
    for (const [k, vals] of Object.entries(ENUM)) if (e[k] && !vals.includes(e[k])) bad(`${k} must be one of ${vals.join(', ')}`);
    if (e.captured && !/^\d{4}-\d{2}-\d{2}$/.test(e.captured)) bad('captured must be YYYY-MM-DD');
    if (e.reuse === 'ok' && (NOT_OK.test(e.licence ?? '') || ['snippet', 'no'].includes(e.licence_checked))) bad('reuse ok needs a permissive licence read from the repo or terms');
    for (const r of e.related ?? []) if (!existsSync(join(root, `${r}.md`))) bad(`related ${r} does not exist`);
    if (e.app && !existsSync(join(root, '..', e.app))) bad(`app ${e.app} does not exist`);
  }
  return errors;
}

const line = (e) => `- [${e.title}](${e.path}) · ${e.type} · ${e.licence ?? 'n/a'} · ${e.reuse ?? 'n/a'} · ${e.summary}`;
const group = (entries, key) => {
  const g = new Map();
  for (const e of entries) for (const v of [].concat(e[key] ?? [])) g.set(v, [...(g.get(v) ?? []), e]);
  return [...g].sort(([a], [b]) => a.localeCompare(b));
};

export function build(entries) {
  const out = ['# Research index', '', '> Generated by `npm run research`. Edit the entries, not this file. One line per entry: link · type · licence · reuse · what it is.', ''];
  out.push('## By theme');
  for (const [t, es] of group(entries, 'themes')) out.push('', `### ${t}`, ...es.map(line));
  out.push('', '## By tech');
  for (const [t, es] of group(entries, 'tech')) out.push('', `### ${t}`, ...es.map((e) => `- [${e.title}](${e.path})`));
  out.push('', '## Reuse (projects and authors)');
  const third = entries.filter((e) => ['project', 'author'].includes(e.type));
  for (const r of REUSE_ORDER) {
    const es = third.filter((e) => e.reuse === r);
    if (es.length) out.push('', `### ${r === 'ok' ? 'ok' : `**${r}**`}: ${REUSE_NOTE[r]}`, ...es.map(line));
  }
  out.push('', '## Ideas backlog');
  for (const s of ENUM.status) {
    const es = entries.filter((e) => e.type === 'idea' && e.status === s);
    if (es.length) out.push('', `### ${s}`, ...es.map((e) => `${line(e)}${e.app ? ` → ${e.app}` : ''}`));
  }
  out.push('', '## Recent', ...[...entries].sort((a, b) => b.captured.localeCompare(a.captured) || a.path.localeCompare(b.path)).slice(0, 10).map((e) => `${line(e)} · ${e.captured}`));
  return out.join('\n') + '\n';
}

if (import.meta.main) {
  const entries = load();
  const errors = check(entries);
  errors.forEach((m) => console.log(`ERROR ${m}`));
  if (errors.length) process.exit(1);
  const file = join(ROOT, 'INDEX.md');
  const next = build(entries);
  const stale = !existsSync(file) || readFileSync(file, 'utf8') !== next;
  if (process.argv.includes('--check')) {
    if (stale) { console.log('research/INDEX.md is stale: run `npm run research`'); process.exit(1); }
  } else if (stale) { writeFileSync(file, next); console.log(`updated research/INDEX.md (${entries.length} entries)`); }
}
