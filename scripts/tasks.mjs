// Task boards: every <dir>/tasks/NNN-*.md file is one task with YAML-ish front matter.
// `node scripts/tasks.mjs` checks every board, regenerates the table in its README and
// prints what is ready, in progress and waiting on the owner. Skill: .claude/skills/task-board/.
import { readFileSync, writeFileSync, globSync } from 'node:fs';
import { dirname, basename, join } from 'node:path';

export const STATUSES = ['todo', 'in-progress', 'review', 'blocked', 'done'];
const STALE_DAYS = 3;

// Front matter subset: `key: value`, `key: "quoted"`, `key: [a, "b"]`, trailing ` # comment`.
export function parse(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n?/);
  if (!m) return { fm: {}, body: text };
  const fm = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^([\w-]+):\s*(.*)$/);
    if (!kv) continue;
    let v = kv[2].replace(/\s+#\s.*$/, '').trim();
    if (v.startsWith('[')) v = v.slice(1, -1).split(',').map((s) => s.trim().replace(/^"|"$/g, '')).filter(Boolean);
    else v = v.replace(/^"(.*)"$/, '$1');
    fm[kv[1]] = v;
  }
  return { fm, body: text.slice(m[0].length) };
}

export function load(dir) {
  return globSync(join(dir, '*.md')).filter((f) => basename(f) !== 'README.md').sort().map((file) => {
    const { fm } = parse(readFileSync(file, 'utf8'));
    return { ...fm, depends_on: fm.depends_on || [], touches: fm.touches || [], file };
  });
}

// Two touch patterns clash when one's fixed prefix (before any * or <) starts the other.
// shortcut: prefix match only, good enough for folder-shaped `touches`; use a glob lib if that stops holding.
const stem = (p) => p.split(/[*<]/)[0];
export const clash = (a, b) => a.touches.some((x) => b.touches.some((y) => stem(x).startsWith(stem(y)) || stem(y).startsWith(stem(x))));

export function check(tasks, today = new Date()) {
  const errors = [], warnings = [];
  const byId = new Map();
  for (const t of tasks) {
    for (const k of ['id', 'title', 'status', 'model']) if (!t[k]) errors.push(`${t.file}: missing ${k}`);
    if (t.status && !STATUSES.includes(t.status)) errors.push(`${t.file}: status "${t.status}" not one of ${STATUSES.join('|')}`);
    if (byId.has(t.id)) errors.push(`${t.file}: duplicate id ${t.id}`);
    byId.set(t.id, t);
  }
  for (const t of tasks) for (const d of t.depends_on) if (!byId.has(d)) errors.push(`${t.file}: depends on unknown task ${d}`);
  // Cycle check: depth-first walk with a "visiting" mark.
  const mark = new Map();
  const visit = (t, path) => {
    if (mark.get(t.id) === 'done') return;
    if (mark.get(t.id) === 'visiting') { errors.push(`dependency cycle: ${[...path, t.id].join(' → ')}`); return; }
    mark.set(t.id, 'visiting');
    for (const d of t.depends_on) if (byId.has(d)) visit(byId.get(d), [...path, t.id]);
    mark.set(t.id, 'done');
  };
  tasks.forEach((t) => visit(t, []));
  const active = tasks.filter((t) => t.status === 'in-progress');
  for (const t of active) {
    if (t.claimed && (today - new Date(t.claimed)) / 864e5 > STALE_DAYS) warnings.push(`${t.id} in progress since ${t.claimed}: stale? check git log before reclaiming`);
    for (const u of active) if (t.id < u.id && clash(t, u)) warnings.push(`${t.id} and ${u.id} are both in progress and touch the same paths`);
  }
  return { errors, warnings };
}

// Ready = todo with every dependency done. Batches = greedy groups with no overlapping `touches`.
export function ready(tasks) {
  const done = new Set(tasks.filter((t) => t.status === 'done').map((t) => t.id));
  const list = tasks.filter((t) => t.status === 'todo' && t.depends_on.every((d) => done.has(d)));
  const batches = [];
  for (const t of list) {
    const b = batches.find((g) => g.every((u) => !clash(t, u)));
    b ? b.push(t) : batches.push([t]);
  }
  return { list, batches };
}

const START = '<!-- board:start (generated by `npm run tasks`; edit the task files, not this table) -->';
const END = '<!-- board:end -->';

export function table(tasks) {
  const rows = tasks.map((t) => `| ${t.id} | [${t.title}](${basename(t.file)}) | ${t.model.split(/[ (]/)[0]} | ${t.depends_on.join(', ') || '—'} | ${t.status} |`);
  return ['| # | Task | Model | Needs | Status |', '|---|---|---|---|---|', ...rows].join('\n');
}

export function writeBoard(dir, tasks) {
  const file = join(dir, 'README.md');
  const text = readFileSync(file, 'utf8');
  const i = text.indexOf(START), j = text.indexOf(END);
  if (i < 0 || j < i) return false;
  const next = text.slice(0, i + START.length) + '\n' + table(tasks) + '\n' + text.slice(j);
  if (next !== text) writeFileSync(file, next);
  return next !== text;
}

if (import.meta.main) {
  const checkOnly = process.argv.includes('--check');
  const dirs = process.argv.slice(2).filter((a) => !a.startsWith('--'));
  const boards = dirs.length ? dirs : globSync('**/tasks/README.md', { exclude: (p) => /^(node_modules|dist)\b/.test(p) }).map(dirname);
  let failed = false;
  for (const dir of boards) {
    const tasks = load(dir);
    const { errors, warnings } = check(tasks);
    const { batches } = ready(tasks);
    const count = Object.fromEntries(STATUSES.map((s) => [s, tasks.filter((t) => t.status === s).length]));
    console.log(`\n## ${dir}  ${STATUSES.map((s) => `${s} ${count[s]}`).join(' · ')}`);
    errors.forEach((e) => console.log(`  ERROR ${e}`));
    warnings.forEach((w) => console.log(`  warn  ${w}`));
    const line = (t) => `${t.id} ${t.title} [${t.model.split(/[ (]/)[0]}]`;
    for (const s of ['in-progress', 'review', 'blocked']) for (const t of tasks.filter((x) => x.status === s)) console.log(`  ${s.padEnd(11)} ${line(t)}${s === 'review' ? '  ← waiting on owner' : ''}`);
    batches.forEach((b, n) => console.log(`  ready ${n + 1}    ${b.map(line).join('  |  ')}`));
    if (errors.length) failed = true;
    else if (!checkOnly && writeBoard(dir, tasks)) console.log(`  board updated: ${dir}/README.md`);
  }
  process.exit(failed ? 1 : 0);
}
